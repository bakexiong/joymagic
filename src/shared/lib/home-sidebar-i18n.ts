function translateText(
  value: string | undefined,
  translations?: Record<string, string>,
) {
  if (!value) {
    return value;
  }

  return translations?.[value] ?? value;
}

function localizeSidebarRow(
  row: SidebarRow,
  localeCopy?: LocaleSidebarCopy,
): SidebarRow {
  if (row.kind !== "link" && row.kind !== "heading") {
    return row;
  }

  return {
    ...row,
    title: translateText(row.title, localeCopy?.titles) ?? row.title,
    ...("badge" in row && row.badge
      ? { badge: translateText(row.badge, localeCopy?.badges) ?? row.badge }
      : {}),
  };
}

function isSidebarLink(
  row: SidebarRow,
): row is Extract<SidebarRow, { kind: "link" }> {
  return row.kind === "link";
}

export function localizeHomeSidebar(
  data: HomeSidebarData | undefined,
  locale: string,
): HomeSidebarData | undefined {
  if (!data) {
    return data;
  }

  const localeCopy = SIDEBAR_COPY[locale] ?? SIDEBAR_COPY.en;
  const effectRows = data.items.filter(
    (row) =>
      isSidebarLink(row) &&
      (row.url === "/video-effect" ||
        row.url === "/image-effect" ||
        row.url === AI_EFFECT_ROW.url),
  );
  const effectSeed =
    effectRows.find(
      (row) => isSidebarLink(row) && row.url !== AI_EFFECT_ROW.url,
    ) ?? effectRows[0];
  const items = data.items.filter(
    (row) =>
      !(
        isSidebarLink(row) &&
        (row.url === "/video-effect" ||
          row.url === "/image-effect" ||
          row.url === AI_EFFECT_ROW.url)
      ),
  );
  const aiEffectRow: SidebarRow = {
    ...AI_EFFECT_ROW,
    icon: isSidebarLink(effectSeed)
      ? (effectSeed.icon ?? AI_EFFECT_ROW.icon)
      : AI_EFFECT_ROW.icon,
    badge:
      isSidebarLink(effectSeed) && effectSeed.badge
        ? effectSeed.badge
        : AI_EFFECT_ROW.badge,
    badgeVariant:
      isSidebarLink(effectSeed) && effectSeed.badgeVariant
        ? effectSeed.badgeVariant
        : AI_EFFECT_ROW.badgeVariant,
  };
  const imageIndex = items.findIndex(
    (row) => isSidebarLink(row) && row.url === "/ai-image-generator",
  );
  items.splice(imageIndex >= 0 ? imageIndex + 1 : items.length, 0, aiEffectRow);

  return {
    ...data,
    upgrade: data.upgrade
      ? {
          ...data.upgrade,
          title:
            translateText(data.upgrade.title, {
              "Upgrade Now": localeCopy.upgradeTitle ?? data.upgrade.title,
              Prcing: localeCopy.upgradeTitle ?? data.upgrade.title,
            }) ?? data.upgrade.title,
        }
      : data.upgrade,
    items: items.map((row) => localizeSidebarRow(row, localeCopy)),
  };
}

export function translateHomeSidebarText(
  locale: string,
  value: string | undefined,
) {
  const localeCopy = SIDEBAR_COPY[locale] ?? SIDEBAR_COPY.en;
  return translateText(value, localeCopy.titles) ?? value;
}

